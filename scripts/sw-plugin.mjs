import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

function listFiles(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? listFiles(full) : [full];
  });
}

const WORKER = (version, urls, base) => `// Generated by scripts/sw-plugin.ts; do not edit.
const VERSION = ${JSON.stringify(version)};
const CACHE = "dungeon-desktop-" + VERSION;
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  // No skipWaiting here: the new worker waits until the DM accepts the update prompt.
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
});

self.addEventListener("message", (event) => {
  if (event.data && event.data.type === "SKIP_WAITING") self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("dungeon-desktop-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET" || new URL(request.url).origin !== self.location.origin) return;
  event.respondWith(
    caches.open(CACHE).then(async (cache) => {
      const hit = await cache.match(request, { ignoreSearch: request.mode === "navigate", ignoreVary: true });
      if (hit) return hit;
      if (request.mode === "navigate") return (await cache.match(${JSON.stringify(base + "index.html")})) || fetch(request);
      return fetch(request);
    }),
  );
});
`;

/** Build-only: writes dist/sw.js that precaches every emitted file (app shell, chunks, bundled SRD data). */
export function offlineServiceWorker() {
  let outDir = "dist";
  let base = "/";
  return {
    name: "offline-service-worker",
    apply: "build",
    configResolved(config) {
      outDir = join(config.root, config.build.outDir);
      base = config.base;
    },
    closeBundle() {
      const files = listFiles(outDir).filter((f) => relative(outDir, f) !== "sw.js").sort();
      const hash = createHash("sha256");
      const urls = [base];
      for (const file of files) {
        hash.update(relative(outDir, file)).update(readFileSync(file));
        urls.push(base + relative(outDir, file).split(sep).join("/"));
      }
      writeFileSync(join(outDir, "sw.js"), WORKER(hash.digest("hex").slice(0, 12), urls, base));
    },
  };
}
